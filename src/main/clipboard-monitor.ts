/**
 * Clipboard history collector.
 *
 * A launcher that quietly records everything the user copies is a privacy
 * liability: clipboards routinely carry passwords, 2FA codes and API tokens.
 * Three rules keep this feature honest:
 *
 *   1. Polling only runs while the clipboard module is actually enabled in
 *      settings. Previously the watcher ran unconditionally, so users who had
 *      turned the feature off were still being recorded.
 *   2. Entries that the source application marked as sensitive are skipped
 *      (password managers set a per-platform "concealed" hint).
 *   3. History is memory-only, capped, and expires — see `search-engine.ts`.
 */

import { clipboard } from 'electron';
import { getConfig } from './config';
import { clearClipboardHistory, recordClipboardEntry } from './search-engine';

const POLL_INTERVAL_MS = 1_000;

/**
 * Per-platform markers that mean "do not put this in a clipboard manager".
 * These are the de-facto standards honoured by KeePassXC, Bitwarden, 1Password
 * and friends.
 */
const SENSITIVE_CLIPBOARD_FORMATS = [
  // KDE / KeePassXC / Bitwarden on Linux.
  'x-kde-passwordManagerHint',
  'application/x-kde-passwordManagerHint',
  // macOS.
  'org.nspasteboard.ConcealedType',
  'org.nspasteboard.AutoGeneratedType',
  // Windows clipboard-history opt-out formats.
  'ExcludeClipboardContentFromMonitorProcessing',
  'CanIncludeInClipboardHistory',
  'CanUploadToCloudClipboard',
];

let timer: NodeJS.Timeout | null = null;

/**
 * Best-effort detection of a "secret" clipboard payload. Formats are advisory
 * and platform-specific, so a miss is possible — the retention limit is the
 * backstop.
 */
function isSensitiveClipboard(): boolean {
  let formats: string[] = [];
  try {
    formats = clipboard.availableFormats();
  } catch {
    return false;
  }

  const lowered = formats.map((f) => f.toLowerCase());
  return SENSITIVE_CLIPBOARD_FORMATS.some((marker) =>
    lowered.includes(marker.toLowerCase())
  );
}

function poll(): void {
  const config = getConfig();
  if (!config.search.enableClipboard) return;

  if (config.privacy.clipboardIgnoreSensitive && isSensitiveClipboard()) return;

  let text = '';
  try {
    text = clipboard.readText();
  } catch {
    return;
  }
  recordClipboardEntry(text);
}

/**
 * Starts or stops the watcher to match the current settings. Safe to call
 * repeatedly; the `save-settings` handler calls it after every save so that
 * turning the module off takes effect immediately (and drops what was already
 * collected).
 */
export function syncClipboardMonitoring(): void {
  const enabled = getConfig().search.enableClipboard;

  if (!enabled) {
    if (timer) {
      clearInterval(timer);
      timer = null;
    }
    // Disabling the module should also forget what it already saw, otherwise
    // the toggle only hides the data.
    clearClipboardHistory();
    return;
  }

  if (timer) return;
  timer = setInterval(poll, POLL_INTERVAL_MS);
}

export function stopClipboardMonitoring(): void {
  if (timer) {
    clearInterval(timer);
    timer = null;
  }
  clearClipboardHistory();
}
